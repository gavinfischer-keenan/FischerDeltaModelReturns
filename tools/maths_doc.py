"""Write docs/maths.md from the register of maths (python/fdmr_plugins/registry.py).

The register names, for each kind of water and each part of its working, the
maths that does it, where it comes from and the code that runs it; each cycle
records the maths every reach ran from the same register. So this document
cannot say anything the code does not.

Usage:
  python tools/maths_doc.py           write docs/maths.md
  python tools/maths_doc.py --check   fail if docs/maths.md is out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))

from fdmr_plugins.registry import CANDIDATES, CHECKS, REGISTER  # noqa: E402

KINDS = {
    "river-routing": "Rivers, from a dam's release down past gauges (one dimension along the channel)",
    "1d-tidal-network": "A tidal channel network, such as the Delta (DSM2, one dimension per channel)",
    "2d-field": "An open bay, on a mesh (two dimensions, depth-averaged)",
    "canal-network": "Export canals, carried from their intake",
    "all": "Every kind of water",
}


def linked(s: str) -> str:
    """Each ref:<key> as a link to its entry in references.md."""
    return re.sub(r"\bref:([a-z][a-z0-9_]*)", r"[\1](references.md#\1)", s)


def build() -> str:
    out = ["# The maths", "",
           "What calculation runs in each kind of water, part by part, where each comes from, and",
           "the code that runs it. Generated by `tools/maths_doc.py` from the register of maths",
           "(`python/fdmr_plugins/registry.py`), which each published cycle also records reach by",
           "reach (`index.json`, `reaches[].maths`). A region may choose another registered",
           "implementation of a part; an unknown choice is refused. Each maths passes the standard",
           "problems listed under its kind (the tests that must pass, and the checks against",
           "stations an external model is judged by). Do not edit by hand.", ""]
    for kind, parts in REGISTER.items():
        out += [f"## {kind}", "", KINDS.get(kind, ""), "",
                "| Part | Maths | What it does | Source | Code |", "| --- | --- | --- | --- | --- |"]
        for part, impls in parts.items():
            for i, m in enumerate(impls):
                name = f"**{m.name}**" + (" (default)" if i == 0 and len(impls) > 1 else "")
                cells = [part, name, m.what, linked(m.source), f"`{m.code}`"]
                out.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        out += ["", "Standard problems passed:", ""]
        for part, impls in parts.items():
            for m in impls:
                out.append(f"- **{m.name}**: " + "; ".join(
                    c[len("check: "):] if c.startswith("check: ") else f"`{c.split('::')[1]}` ({c.split('::')[0]})"
                    for c in CHECKS.get(m.name, ())))
        out.append("")
    out += ["## Candidates, not in the live model", "",
            "Maths or settings that cannot be sourced yet (issue #26). None of them runs: each would be tried, "
            "judged on data it was not chosen on, and adopted by hand with its source. A registered alternative "
            "above can be tried on a hindcast, labelled and scored apart, with `python -m fdmr_runner.trial`.", "",
            "| Kind | Part | Candidate | What is known | Why it is not in | Issue |", "| --- | --- | --- | --- | --- | --- |"]
    for c in CANDIDATES:
        cells = [c.kind, c.part, f"**{c.name}**", linked(c.known), c.why_not, c.issue]
        out.append("| " + " | ".join(x.replace("|", "\\|") for x in cells) + " |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text, path = build(), ROOT / "docs" / "maths.md"
    if "--check" in argv:
        ok = path.exists() and path.read_text(encoding="utf-8") == text
        print("docs/maths.md", "ok" if ok else "is out of date: run python tools/maths_doc.py")
        return 0 if ok else 1
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
