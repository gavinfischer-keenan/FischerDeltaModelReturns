"""The references: every paper, book, report, data set and program the model
draws on, and where each is used.

references.toml (at the repository's root) holds each reference once, in
full. Anywhere it is used (code, region settings, documents, the DSM2 patch)
cites it by key as `ref:<key>`, as in `ref:achete2015`. This tool finds every
citation and writes:

  ui/public/references.json   the references and, for each, every place it is
                              cited (file, line, the line's text), for the
                              site's references page (references.html)
  docs/references.md          the same, for reading in the repository

Usage:
  python tools/references.py           write both files
  python tools/references.py --check   fail if a citation names no reference,
                                       a reference is cited nowhere or lacks a
                                       field, or either file is out of date

Standard library only.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKEN = re.compile(r"\bref:([a-z][a-z0-9_]*)")
SCAN = {".py", ".rs", ".toml", ".md", ".sh", ".patch", ".html", ".ts", ".svelte", ".f90"}
SKIP_DIRS = {"target", "node_modules", "__pycache__", "dist", ".venv", ".git", "pkg"}
SKIP_FILES = {"references.toml", "docs/references.md", "ui/public/references.json", "tools/references.py"}
KINDS = {"paper", "book", "chapter", "report", "standard", "data", "software", "web"}
REQUIRED = ("authors", "year", "title", "kind")


def load(root: Path = ROOT) -> dict[str, dict]:
    return tomllib.loads((root / "references.toml").read_text(encoding="utf-8"))


def citations(root: Path = ROOT) -> dict[str, list[dict]]:
    """Every `ref:<key>` in the repository: key -> [{file, line, text}]."""
    out: dict[str, list[dict]] = {}
    # The repository's own files (git's list), in plain text order, so the
    # result is the same on every machine; every file where git is absent.
    import subprocess

    try:
        rels = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout.split("\n")
    except (OSError, subprocess.CalledProcessError):
        rels = [p.relative_to(root).as_posix() for p in root.rglob("*")]
    for rel in sorted(r for r in rels if r):
        p = root / rel
        if not p.is_file() or p.suffix not in SCAN or SKIP_DIRS & set(Path(rel).parts) or rel in SKIP_FILES:
            continue
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for m in TOKEN.finditer(line):
                text = line.strip().lstrip("#/!*- ").strip()
                out.setdefault(m.group(1), []).append({"file": rel, "line": i, "text": text[:200]})
    return out


def problems(refs: dict[str, dict], cited: dict[str, list[dict]]) -> list[str]:
    out = []
    for key in sorted(set(cited) - set(refs)):
        where = ", ".join(f"{c['file']}:{c['line']}" for c in cited[key][:3])
        out.append(f"ref:{key} is cited ({where}) but not in references.toml")
    for key, r in refs.items():
        if key not in cited:
            out.append(f"{key} is in references.toml but cited nowhere")
        for f in REQUIRED:
            if not r.get(f):
                out.append(f"{key} has no {f}")
        if r.get("kind") not in KINDS:
            out.append(f"{key}: kind {r.get('kind')!r} is not one of {sorted(KINDS)}")
        if r.get("cited_via") and r["cited_via"] not in refs:
            out.append(f"{key}: cited_via {r['cited_via']!r} is not in references.toml")
        if not (r.get("doi") or r.get("url") or r.get("cited_via")):
            out.append(f"{key} has no doi, url or cited_via, so a reader cannot find it")
        if not r.get("checked"):
            out.append(f"{key} has no `checked` (how and when the citation was confirmed)")
    return out


def citation_text(r: dict) -> str:
    """The reference as it is printed: authors (year). title. where. doi/url."""
    s = f"{r['authors']} ({r['year']}). {r['title']}."
    if r.get("in"):
        s += f" {r['in']}."
    if r.get("isbn"):
        s += f" ISBN {r['isbn']}."
    if r.get("doi"):
        s += f" https://doi.org/{r['doi']}"
    elif r.get("url"):
        s += f" {r['url']}"
    if r.get("cited_via"):
        s += f" (Cited as in {r['cited_via']}.)"
    return s


def build(refs: dict[str, dict], cited: dict[str, list[dict]]) -> tuple[str, str]:
    order = sorted(refs, key=lambda k: (refs[k]["authors"].lower(), refs[k]["year"], k))
    data = {"references": [{"key": k, **refs[k], "citation": citation_text(refs[k]), "used": cited.get(k, [])} for k in order]}
    js = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    md = ["# References", "",
          "Every source the model draws on, in full, and every place it is used. Generated by",
          "`tools/references.py` from `references.toml` and the `ref:<key>` citations in the",
          "repository; do not edit by hand.", ""]
    for k in order:
        r = refs[k]
        md.append(f"## {k}")
        md.append("")
        md.append(citation_text(r))
        md.append("")
        if r.get("note"):
            md.append(f"*{r['note']}*")
            md.append("")
        md.append(f"Checked: {r['checked']}")
        md.append("")
        md.append("Used in:")
        md.append("")
        for c in cited.get(k, []):
            md.append(f"- `{c['file']}:{c['line']}`: {c['text']}")
        md.append("")
    return js, "\n".join(md)


UA = "fdmr-runner/0.1"


def _get_json(url: str, headers: dict | None = None) -> dict:
    import urllib.request

    req = urllib.request.Request(url, headers={"User-Agent": UA, **(headers or {})})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode("utf-8"))


def _words(s: str) -> set[str]:
    return set(re.findall(r"[a-z0-9]+", s.lower())) - {"a", "an", "the", "of", "and", "in", "on", "for", "to", "with"}


def crossref(refs: dict[str, dict]) -> list[str]:
    """Each DOI's Crossref record against the entry: the year, the first
    author's family name and the title's words must agree."""
    import urllib.parse

    out = []
    for key, r in refs.items():
        if not r.get("doi"):
            continue
        try:
            m = _get_json(f"https://api.crossref.org/works/{urllib.parse.quote(r['doi'])}")["message"]
            # the issue's year where it differs from the online one (cited by the issue)
            years = {(m.get(k, {}).get("date-parts") or [[None]])[0][0] for k in ("issued", "published-print", "published-online")}
            year = r["year"] if r["year"] in years else (m.get("issued", {}).get("date-parts") or [[None]])[0][0]
            family = (m.get("author") or [{}])[0].get("family", "")
            title = (m.get("title") or [""])[0]
        except Exception:  # noqa: BLE001  not Crossref's: data sets' DOIs are DataCite's
            try:
                a = _get_json(f"https://api.datacite.org/dois/{urllib.parse.quote(r['doi'])}")["data"]["attributes"]
            except Exception as e:  # noqa: BLE001
                out.append(f"{key}: neither Crossref nor DataCite has doi {r['doi']} ({e})")
                continue
            year = a.get("publicationYear")
            c = (a.get("creators") or [{}])[0]
            family = c.get("familyName") or c.get("name", "")
            title = (a.get("titles") or [{}])[0].get("title", "")
        shared = len(_words(title) & _words(r["title"])) / max(1, len(_words(r["title"])))
        bad = []
        if year != r["year"]:
            bad.append(f"year {year}")
        if family and family.lower() not in r["authors"].lower():
            bad.append(f"first author {family}")
        if shared < 0.8:
            bad.append(f"title {title!r}")
        print(f"{key:24s} {'ok' if not bad else 'DIFFERS: ' + '; '.join(bad)}")
        if bad:
            out.append(f"{key}: Crossref's record differs: {'; '.join(bad)}")
    return out


def find(text: str) -> None:
    """Candidates for a paper from Consensus's search (its key in
    $CONSENSUS_API_KEY or ~/.config/fdmr/consensus-api-key), with DOI,
    journal, volume and pages, to fill in an entry."""
    import os
    import urllib.parse

    key = os.environ.get("CONSENSUS_API_KEY") or (Path.home() / ".config" / "fdmr" / "consensus-api-key").read_text().strip()
    d = _get_json("https://api.consensus.app/v1/search?" + urllib.parse.urlencode({"query": text}), {"x-api-key": key})
    for p in d.get("results", [])[:5]:
        print(f"{p.get('publish_year')}  {'; '.join(p.get('authors') or [])}\n      {p.get('title')}\n"
              f"      {p.get('journal_name')} {p.get('volume') or ''} {p.get('pages') or ''}  doi {p.get('doi')}\n")


def main(argv: list[str]) -> int:
    if argv[:1] == ["--find"]:
        find(" ".join(argv[1:]))
        return 0
    refs, cited = load(), citations()
    if "--crossref" in argv:
        errs = crossref(refs)
        return 1 if errs else 0
    js, md = build(refs, cited)
    errs = problems(refs, cited)
    jp, mp = ROOT / "ui" / "public" / "references.json", ROOT / "docs" / "references.md"
    if "--check" in argv:
        if not jp.exists() or jp.read_text(encoding="utf-8") != js:
            errs.append("ui/public/references.json is out of date: run python tools/references.py")
        if not mp.exists() or mp.read_text(encoding="utf-8") != md:
            errs.append("docs/references.md is out of date: run python tools/references.py")
        for e in errs:
            print(e)
        print(f"{len(refs)} references, {sum(len(v) for v in cited.values())} citations: {'FAILED' if errs else 'ok'}")
        return 1 if errs else 0
    jp.write_text(js, encoding="utf-8", newline="\n")
    mp.write_text(md, encoding="utf-8", newline="\n")
    for e in errs:
        print("warning:", e)
    print(f"wrote {jp.relative_to(ROOT)} and {mp.relative_to(ROOT)}: {len(refs)} references, {sum(len(v) for v in cited.values())} citations")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
